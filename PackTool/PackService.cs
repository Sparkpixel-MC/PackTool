using System.Globalization;
using System.IO;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;

namespace PackTool;

public sealed record Snippets(string Server, string Client, string Note);

public sealed record PackOutcome(bool Ok, PackSummary? Summary, Snippets? Snippets,
                                 double Seconds, string? Error);

public delegate void StageCallback(string text);

/// <summary>Port of the Electron main-process pack orchestration (main.js):
/// validate → pack → write pack.mcmeta → build server/client config snippets.</summary>
public static class PackService
{
    private static readonly JsonSerializerOptions Indented = new()
    {
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    public static PackOutcome Pack(string inputDir, string outputDir, string wrapKey,
                                   string mcmetaLock, string mcmetaBind,
                                   StageCallback? stage, PackProgressCallback? progress)
    {
        try
        {
            stage?.Invoke("扫描文件…");
            if (!Directory.Exists(inputDir))
                throw new IOException("输入目录不存在: " + inputDir);

            var started = DateTime.UtcNow;
            var summary = Rssync3.PackPack(inputDir, outputDir, wrapKey, progress);

            stage?.Invoke("生成 pack.mcmeta…");
            if (mcmetaLock.Length > 0 || mcmetaBind.Length > 0)
            {
                var bindList = mcmetaBind.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries);
                var mcmeta = new Dictionary<string, object?>
                {
                    ["pack"] = new Dictionary<string, object?>
                    {
                        ["pack_format"] = 15,
                        ["description"] = "Generated by PackTool",
                    },
                };
                if (mcmetaLock.Length > 0) mcmeta["zbx_rpu_server_lock"] = mcmetaLock;
                if (bindList.Length > 0) mcmeta["zbx_rpu_server_bind"] = bindList;
                var utf8NoBom = new UTF8Encoding(false);
                File.WriteAllText(Path.Combine(inputDir, "pack.mcmeta"),
                    JsonSerializer.Serialize(mcmeta, Indented).Replace("\r\n", "\n"), utf8NoBom);
            }

            var snippets = BuildSnippets(mcmetaLock, wrapKey);
            var seconds = Math.Round((DateTime.UtcNow - started).TotalMilliseconds / 1000.0, 1,
                MidpointRounding.AwayFromZero);
            return new PackOutcome(true, summary, snippets, seconds, null);
        }
        catch (Exception e)
        {
            return new PackOutcome(false, null, null, 0, e.Message);
        }
    }

    /// <summary>Port of main.js buildSnippets(): placeholder URL the owner edits.</summary>
    public static Snippets BuildSnippets(string mcmetaLock, string wrapKey)
    {
        const string url = "https://files.example.com/dist"; // placeholder the owner edits
        var syncChannel = new Dictionary<string, object?>
        {
            ["name"] = "my-server",
            ["url"] = url,
        };
        if (wrapKey.Length > 0) syncChannel["wrapKey"] = wrapKey;

        var server = new Dictionary<string, object?>
        {
            ["serverLock"] = mcmetaLock.Length > 0 ? mcmetaLock : "change-me",
            ["syncChannel"] = syncChannel,
        };
        var client = new Dictionary<string, object?>
        {
            ["bootstrapServers"] = new[] { "mc.example.com" },
        };
        return new Snippets(
            JsonSerializer.Serialize(server, Indented).Replace("\r\n", "\n"),
            JsonSerializer.Serialize(client, Indented).Replace("\r\n", "\n"),
            "把 output 目录的内容上传到任意静态托管，然后把 syncChannel.url 改成实际地址。");
    }

    public static string FormatSummary(PackSummary s, double seconds) =>
        string.Create(CultureInfo.InvariantCulture,
            $"完成！{s.FileCount} 个文件、{s.DirCount} 个目录，耗时 {seconds.ToString("0.0", CultureInfo.InvariantCulture)}s");
}
