'use strict';
const { app, BrowserWindow, ipcMain, dialog } = require('electron');
const path = require('path');
const fs = require('fs');
const rssync3 = require('./rssync3');

let win;

function createWindow() {
  win = new BrowserWindow({
    width: 900,
    height: 680,
    minWidth: 760,
    minHeight: 560,
    backgroundColor: '#0f141a',
    title: 'Resource-Sync PackTool',
    autoHideMenuBar: true,
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
    },
  });
  win.loadFile('renderer/index.html');
}

app.whenReady().then(createWindow);
app.on('window-all-closed', () => app.quit());

// ---- IPC ------------------------------------------------------------------

ipcMain.handle('pick-directory', async () => {
  const result = await dialog.showOpenDialog(win, { properties: ['openDirectory'] });
  return result.canceled ? null : result.filePaths[0];
});

ipcMain.handle('generate-wrap-key', () => rssync3.generateWrapKey());

ipcMain.handle('pack', async (event, { inputDir, outputDir, wrapKey, mcmetaLock, mcmetaBind }) => {
  const send = (payload) => win.webContents.send('pack-progress', payload);
  try {
    if (!fs.existsSync(inputDir) || !fs.statSync(inputDir).isDirectory()) {
      throw new Error('输入目录不存在: ' + inputDir);
    }
    send({ type: 'stage', text: '扫描文件…' });
    const started = Date.now();
    const summary = await rssync3.packPack(inputDir, outputDir, wrapKey, {}, (done, total, name) => {
      send({ type: 'progress', done, total, name });
    });

    send({ type: 'stage', text: '生成 pack.mcmeta…' });
    if (mcmetaLock || mcmetaBind) {
      const bindList = (mcmetaBind || '').split(',').map(s => s.trim()).filter(Boolean);
      const mcmeta = {
        pack: { pack_format: 15, description: 'Generated by PackTool' },
        ...(mcmetaLock ? { zbx_rpu_server_lock: mcmetaLock } : {}),
        ...(bindList.length ? { zbx_rpu_server_bind: bindList } : {}),
      };
      fs.writeFileSync(path.join(inputDir, 'pack.mcmeta'), JSON.stringify(mcmeta, null, 2), 'utf8');
    }

    const snippets = buildSnippets(outputDir, wrapKey, mcmetaLock);
    send({ type: 'done', summary: { ...summary, seconds: ((Date.now() - started) / 1000).toFixed(1) }, snippets });
    return { ok: true };
  } catch (e) {
    send({ type: 'error', message: String(e.message || e) });
    return { ok: false, error: String(e.message || e) };
  }
});

function buildSnippets(outputDir, wrapKey, mcmetaLock) {
  const backslashes = outputDir.includes('\\');
  const url = 'https://files.example.com' + '/dist'; // placeholder the owner edits
  const server = {
    serverLock: mcmetaLock || 'change-me',
    syncChannel: {
      name: 'my-server',
      url,
      ...(wrapKey ? { wrapKey } : {}),
    },
  };
  const client = { bootstrapServers: ['mc.example.com'] };
  return {
    server: JSON.stringify(server, null, 2),
    client: JSON.stringify(client, null, 2),
    note: '把 output 目录的内容上传到任意静态托管，然后把 syncChannel.url 改成实际地址。',
  };
}
